# -*- coding: utf-8 -*-
"""Свобода игрока: «это реальная жизнь, просто в другом мире».

Жалоба игрока: «не обязательно идти по сюжету — мир открытый. Я бы например рыбачил
очень много или занимался садом… расслабляться, побеждать боссов или обычно жить — его
выбор».

Что было не так: фоновый «автономный мастер» считал ПОВТОР действия признаком того, что
игрок «застрял», и навязывал ему цель. Двадцать дней рыбалки подряд выглядели для движка
как тупик, и игра начинала подталкивать: «а вот тебе зацеп!». Плюс любой долгий отрезок
без квестов тоже считался «бродяжничеством».

Стало:
  * повтор БЫТОВЫХ дел (рыбалка, сад, готовка, уборка, сон, чтение…) — не застревание
    вообще: это нормальная жизнь, и мастер молчит;
  * отсутствие квестов тоже не повод вмешиваться — целиком убрано;
  * сигнал остался только на настоящую монотонность «деятельных» действий;
  * мир при этом не замирает: раз в N ходов мастер просит ОДНО событие жизни
    (новое лицо, открылась лавка, ярмарка, слух) — без угрозы и без «подвига».
"""
from __future__ import annotations

from backend import narrator


# ── быт и досуг не считаются застреванием ───────────────────────────────

def test_fishing_forever_is_life_not_stuck():
    acts = ["рыбачу на Сизой"] * 8
    for turns in (5, 10, 20, 50, 200):
        assert narrator.master_stuck_reason(acts, 0, turns) is None, \
            "рыбалка не должна вызывать мастера — это выбор игрока"


def test_garden_and_chores_are_life():
    acts = ["поливаю грядки", "полю грядки", "сею семена", "поливаю грядки",
            "собираю урожай", "поливаю грядки"]
    assert narrator.master_stuck_reason(acts, 0, 30) is None


def test_varied_life_without_quests_is_never_drift():
    varied = ["гуляю по рынку", "говорю с Мартой", "сижу у реки", "чиню лодку",
              "слушаю истории у костра", "сплю до обеда"]
    for turns in (10, 15, 40, 100):
        assert narrator.master_stuck_reason(varied, 0, turns) is None


# ── но настоящая монотонность по-прежнему видна ─────────────────────────

def test_real_repetition_still_detected():
    """Одно и то же «деятельное» действие без перемен — всё же повод оживить."""
    acts = ["обыскиваю сундук", "обыскиваю сундук", "обыскиваю сундук",
            "обыскиваю сундук", "обыскиваю сундук"]
    assert narrator.master_stuck_reason(acts, 1, 5) == "repetition"


def test_mixed_leisure_and_effort_not_stuck():
    acts = ["рыбачу", "иду к руинам", "смотрю на стену", "возвращаюсь домой"]
    assert narrator.master_stuck_reason(acts, 0, 30) is None


# ── промпт мастера знает про «живой мир» ────────────────────────────────

def test_growth_prompt_is_about_life_not_threat():
    msgs = narrator.master_messages({"player": {"name": "Т", "hp": 10, "max_hp": 10,
                                                "mp": 5, "max_mp": 5, "stats": {}},
                                     "location": "start"},
                                    "growth", "Действие игрока: рыбачу")
    text = "\n".join(m["content"] for m in msgs)
    assert "ЖИТЬ" in text or "жит" in text.lower()
    assert "НЕ подбрасывай каждый раз угрозу" in text
    assert "quest" in text, "мастер должен уметь и завести новое дело, а не только болтать"