# -*- coding: utf-8 -*-
"""Действие игрока: он заявляет СВОЁ ДЕЙСТВИЕ, а не состояние мира.

Задумка (жалоба игрока). «я нахожу меч» — не «пытаюсь найти меч»: и то и другое уже
объявляет факт, что меч есть и игрок вот-вот им обзаведётся. Игроку принадлежит только
действие: «осматриваюсь в поисках меча». Появится ли меч, какой именно и не спрятан ли он
в другой руке у хозяйки — решает рассказчик по сцене. Иначе игрок переделывает мир под
себя, и интерес теряется.

Три класса фраз:

  * ДЕЙСТВИЕ («осматриваюсь», «убиваю», «убеждаю») — так и оставляем: он действует сейчас.
  * ИТОГ, глагол УСИЛИЯ («убил», «взломал», «убедил») → «пытаюсь убить/взломать/убедить».
    Это корректно: попытка — тоже действие, исход решает сцена.
  * ИТОГ, глагол ПРИОБРЕТЕНИЯ («нашёл», «взял», «украл», «купил») → ПОИСКОВОЕ ДЕЙСТВИЕ
    «осматриваюсь в поисках X» / «присматриваюсь к X». «Пытаюсь найти» здесь не годится:
    это всё ещё обещание, что объект существует.

Слой детерминированный (без второго вызова модели): каждый ход платить секундами и
рисковать искажением смысла нельзя. Исходная фраза всегда сохраняется в `original` и уходит
в промпт рядом — рассказчик видит и буквальную просьбу, и переведённое действие.
"""
from __future__ import annotations

import re

# Глаголы-ИТОГИ (прошедшее время) и их инфинитив.
_PAST: dict[str, str] = {
    # приобретение (→ поисковое действие)
    "нашёл": "найти", "нашел": "найти", "нашли": "найти", "разыскал": "разыскать",
    "обнаружил": "обнаружить", "отыскал": "отыскать", "выследил": "выследить",
    "взял": "взять", "подобрал": "подобрать", "забрал": "забрать", "украл": "украсть",
    "выкрал": "выкрасть", "отобрал": "отобрать", "обыскал": "обыскать", "отнял": "отнять",
    "стянул": "стянуть", "прибрал": "прибрать", "купил": "купить", "выпросил": "выпросить",
    "подкупил": "подкупить", "выиграл": "выиграть",
    # усилие/угроза (→ «пытаюсь …»)
    "убил": "убить", "убила": "убить", "победил": "победить", "одолел": "одолеть",
    "уничтожил": "уничтожить", "прикончил": "прикончить", "добил": "добить",
    "ударил": "ударить", "срубил": "срубить", "отрубил": "отрубить", "кинул": "кинуть",
    "бросил": "бросить", "резанул": "резануть", "пронзил": "пронзить", "ранил": "ранить",
    "оглушил": "оглушить", "обезоружил": "обезоружить",
    "убедил": "убедить", "уговорил": "уговорить", "обманул": "обмануть", "запугал": "запугать",
    "сторговался": "сторговаться", "очаровал": "очаровать", "припугнул": "припугнуть",
    "взломал": "взломать", "открыл": "открыть", "вскрыл": "вскрыть", "запер": "запереть",
    "взобрался": "взобраться", "спрятался": "спрятаться", "скрылся": "скрыться",
    "пробрался": "пробраться", "прошёл": "пройти", "прошел": "пройти", "прокрался": "прокрасться",
    "сделал": "сделать", "создал": "создать", "смастерил": "смастерить", "сварил": "сварить",
    "вылечил": "вылечить", "сломал": "сломать", "починил": "починить", "зажёг": "зажечь",
}

# Глаголы приобретения: их «пытаюсь X» всё ещё обещает существование объекта.
# Шаблон {obj} — объект в ИСХОДНОМ падеже, поэтому формулировки не требуют склонения:
# «в поисках меч» → «разглядываю ищу меч» звучало бы криво, а «разглядываю… нет:
# берём обороты, где падеж не важен:
#   «ищу меч» — нет (обещает), «разглядываю меч» — это ДЕЙСТВИЕ и падеж правильный.
_ACQUIRE: dict[str, str] = {
    "найти": "разглядываю {obj}", "обнаружить": "разглядываю {obj}",
    "отыскать": "разглядываю {obj}", "разыскать": "разглядываю {obj}",
    "выследить": "разглядываю {obj}",
    "взять": "разглядываю {obj}", "подобрать": "разглядываю {obj}", "забрать": "разглядываю {obj}",
    "украсть": "разглядываю {obj}", "выкрасть": "разглядываю {obj}", "отобрать": "разглядываю {obj}",
    "отнять": "разглядываю {obj}", "стянуть": "разглядываю {obj}", "прибрать": "разглядываю {obj}",
    "обыскать": "обыскиваю {obj}", "купить": "разглядываю {obj}",
    "выпросить": "прошу {obj}", "подкупить": "переговариваюсь насчёт {obj}",
    "выиграть": "играю на {obj}",
}

# Объект не назван: «нашёл» без дополнения → «осматриваюсь».
_ACQUIRE_NO_OBJ = "осматриваюсь"

_ATTEMPT = re.compile(
    r"\b(пыта|пробу|хочу|намерева|намерен|собираюсь|постара|стараю|удалось|удаётся|удается|ищу|обыскива|осматрива|присматрива)",
    re.I,
)
_QUESTION = re.compile(r"\?\s*$")
_WORD = re.compile(r"[А-Яа-яЁёA-Za-z]+")


def _verb_sentence(verb: str) -> str:
    """«нашёл» → «осматриваюсь» / «убил» → «пытаюсь убить» (без объекта)."""
    inf = _PAST.get(verb.lower())
    if not inf:
        return verb
    if inf in _ACQUIRE:
        return _ACQUIRE_NO_OBJ
    return f"пытаюсь {inf}"


def normalize_intent(action: str) -> dict:
    """Переводит действие игрока в форму, не заявляющую состояние мира.

    Возвращает `{"text", "original", "changed", "replaced", "kind"}`:
      kind — "acquire" (поисковое действие), "attempt" (попытка), "process"/"question"/"empty".
    """
    raw = (action or "").strip()
    if not raw:
        return {"text": raw, "original": raw, "changed": False, "replaced": 0, "kind": "empty"}
    if _QUESTION.search(raw):
        return {"text": raw, "original": raw, "changed": False, "replaced": 0, "kind": "question"}
    if _ATTEMPT.search(raw):
        return {"text": raw, "original": raw, "changed": False, "replaced": 0, "kind": "process"}

    tokens = list(_WORD.finditer(raw))
    hits = [(i, m) for i, m in enumerate(tokens) if m.group(0).lower() in _PAST]
    if not hits:
        return {"text": raw, "original": raw, "changed": False, "replaced": 0, "kind": "process"}

    kind = "attempt"
    for idx, m in hits:
        inf = _PAST[m.group(0).lower()]
        tpl = _ACQUIRE.get(inf)
        head = raw[:m.start()]
        if not tpl:
            # усилие: глагол → «пытаюсь + инфинитив», хвост (объект) не трогаем
            tail = raw[m.end():]
            raw = f"{head}пытаюсь {inf}{tail}"
            continue
        # приобретение: объект — всё после глагола до союза/знака препинания
        tail = raw[m.end():]
        obj_m = re.match(r"\s*([^\s.!?,;]+(?:\s+[^\s.!?,;]+)*?)(?=\s+(?:и|а|но|затем|потом)\b|[.!?,;]|$)", tail, re.I)
        obj = (obj_m.group(1).strip() if obj_m else "").strip()
        rest = tail[obj_m.end():] if obj_m else tail
        kind = "acquire"
        if obj:
            text = tpl.format(obj=obj)
        else:
            text = _ACQUIRE_NO_OBJ
        raw = f"{head}{text}{rest}"
        # пересобираем: позиции токенов после замены больше не годятся — дальше идём по фразу
        break

    text = re.sub(r"\s{2,}", " ", raw).strip()
    text = re.sub(r"\s+([.!?,;])", r"\1", text)
    return {"text": text, "original": action.strip(), "changed": True,
            "replaced": len(hits), "kind": kind}
